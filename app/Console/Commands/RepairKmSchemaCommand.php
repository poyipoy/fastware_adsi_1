<?php

namespace App\Console\Commands;

use App\Services\KnowledgeManagement\KmSchemaAuditService;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use RuntimeException;
use Throwable;

final class RepairKmSchemaCommand extends Command
{
    private const REPAIR_JOURNAL_VERSION = 1;

    protected $signature = 'km:repair-schema
        {manifest : Audit manifest path generated by km:audit-schema --write-manifest}
        {--apply : Apply the deterministic repair plan}
        {--restore : Restore the original rows recorded in an applied manifest}';

    protected $description = 'Repair duplicate and orphan KM rows from a checksum-verified private manifest.';

    private const REPAIR_ACTIONS = [
        'km_pengajuans.id_user' => ['km_pengajuans', 'id_user', 'set_null'],
        'km_pengajuans.id_km_kategori' => ['km_pengajuans', 'id_km_kategori', 'set_null'],
        'km_transaksis.id_user' => ['km_transaksis', 'id_user', 'delete'],
        'km_transaksis.id_km_pengajuan' => ['km_transaksis', 'id_km_pengajuan', 'delete'],
        'km_transaksis.modified_by' => ['km_transaksis', 'modified_by', 'set_null'],
        'km_sukas.id_user' => ['km_sukas', 'id_user', 'delete'],
        'km_sukas.id_km_pengajuan' => ['km_sukas', 'id_km_pengajuan', 'delete'],
        'km_insights.id_user' => ['km_insights', 'id_user', 'delete'],
        'km_insights.id_km_pengajuan' => ['km_insights', 'id_km_pengajuan', 'delete'],
        'km_lihat_bukus.id_km_pengajuan' => ['km_lihat_bukus', 'id_km_pengajuan', 'delete'],
        'km_lihat_bukus.id_km_transaksi' => ['km_lihat_bukus', 'id_km_transaksi', 'set_null'],
    ];

    public function handle(KmSchemaAuditService $auditService): int
    {
        try {
            $path = $this->resolveManifestPath((string) $this->argument('manifest'));
            $manifest = $this->loadManifest($path);
            $this->validateTargetDatabase($manifest);
            $journalPath = $this->repairJournalPath($path);
            $journal = $this->loadRepairJournal($auditService, $manifest, $path, $journalPath);
            $this->renderPlan($manifest, $journal);

            $restore = (bool) $this->option('restore');
            $apply = (bool) $this->option('apply');

            if (! $apply && ! $restore) {
                $this->line('Dry-run only. No row was changed. Re-run with --apply after reviewing the manifest.');

                return self::SUCCESS;
            }

            $this->guardMutation($apply, $restore);

            [$journal, $reconciledStatus] = $this->reconcileRepairJournal(
                $auditService,
                $journal,
                $journalPath,
            );
            if ((! $restore && $reconciledStatus === 'applied')
                || ($restore && $reconciledStatus === 'restored')) {
                return self::SUCCESS;
            }

            return $restore
                ? $this->restore($auditService, $manifest, $journal, $journalPath)
                : $this->apply($auditService, $manifest, $path, $journal, $journalPath);
        } catch (Throwable $exception) {
            $this->error('KM schema repair stopped: '.$exception->getMessage());

            return self::FAILURE;
        }
    }

    private function apply(
        KmSchemaAuditService $auditService,
        array $manifest,
        string $manifestPath,
        ?array $journal,
        string $journalPath,
    ): int {
        if (($journal['repair']['status'] ?? null) === 'applied') {
            throw new RuntimeException('This manifest has already been applied. Use --restore before applying it again.');
        }

        $this->assertAutomaticallyRepairable($manifest);
        $this->assertChecksum(
            $auditService->fingerprint()['value'],
            $manifest['database_checksum']['value'] ?? null,
            'The database changed after the audit manifest was created'
        );

        $journal = $this->newRepairJournal($manifest, $manifestPath, [
            'status' => 'applying',
            'started_at' => now()->toIso8601String(),
            'before_checksum' => $manifest['database_checksum']['value'],
        ]);
        $auditService->writeRepairJournal($journal, $journalPath);

        $committingJournal = null;

        $postRepairReport = DB::transaction(function () use (
            $auditService,
            $manifest,
            $journal,
            $journalPath,
            &$committingJournal,
        ): array {
            $this->lockAffectedRows($manifest);
            $this->assertAffectedRowsMatchAuditManifest($manifest);
            $this->detachTransactionViewDependencies($manifest);
            $this->mergeDuplicateTransactions($manifest);
            $this->mergeDuplicateLikes($manifest);
            $this->mergeDuplicateViewCounters($manifest);
            $this->normalizeInvalidViewCounters($manifest);
            $this->repairInvalidAndOrphanReferences($manifest);

            $postRepairReport = $auditService->audit();
            $auditService->assertReadyForHardening($postRepairReport);

            $committingJournal = $journal;
            $committingJournal['repair'] = [
                ...$journal['repair'],
                'status' => 'committing',
                'committing_at' => now()->toIso8601String(),
                'after_checksum' => $postRepairReport['database_checksum']['value'],
                'after_summary' => $postRepairReport['summary'],
                'affected_rows_after' => $this->snapshotAffectedRows($manifest),
            ];

            // This durable state is written while the DB transaction is still
            // open. A crash before/after commit can be reconciled by checksum.
            $auditService->writeRepairJournal($committingJournal, $journalPath);

            return $postRepairReport;
        }, 1);

        if (! is_array($committingJournal)) {
            throw new RuntimeException('Repair transaction committed without a durable committing journal.');
        }

        $appliedJournal = $committingJournal;
        $appliedJournal['repair']['status'] = 'applied';
        $appliedJournal['repair']['completed_at'] = now()->toIso8601String();
        $auditService->writeRepairJournal($appliedJournal, $journalPath);

        $this->info('KM schema repair applied. The post-repair audit is safe for hardening.');
        $this->line("Immutable audit manifest: {$manifestPath}");
        $this->line("Repair journal: {$journalPath}");

        return self::SUCCESS;
    }

    private function restore(
        KmSchemaAuditService $auditService,
        array $manifest,
        ?array $journal,
        string $journalPath,
    ): int {
        if (($journal['repair']['status'] ?? null) !== 'applied') {
            throw new RuntimeException('Restore requires a manifest whose repair status is applied.');
        }

        if ($auditService->hardeningConstraintsInstalled()) {
            throw new RuntimeException(
                'Restore is unavailable after KM hardening constraints are installed. Roll back hardening first.'
            );
        }

        $this->assertChecksum(
            $auditService->fingerprint()['value'],
            $journal['repair']['after_checksum'] ?? null,
            'The database changed after this repair was applied'
        );

        $restoringJournal = null;
        DB::transaction(function () use (
            $auditService,
            $manifest,
            $journal,
            $journalPath,
            &$restoringJournal,
        ): void {
            $this->lockAffectedRows($manifest);
            $this->assertAffectedRowsMatchPostRepairManifest($manifest, $journal);
            $this->restoreDeletedAndMergedRows($manifest);
            $this->restoreNormalizedReferences($manifest);

            $restoredChecksum = $auditService->fingerprint()['value'];
            $this->assertChecksum(
                $restoredChecksum,
                $manifest['database_checksum']['value'] ?? null,
                'Restore completed but the database does not match the original audit state'
            );

            $restoringJournal = $journal;
            $restoringJournal['repair']['status'] = 'restoring';
            $restoringJournal['repair']['restoring_at'] = now()->toIso8601String();
            $restoringJournal['repair']['restored_checksum'] = $restoredChecksum;
            $auditService->writeRepairJournal($restoringJournal, $journalPath);
        }, 1);

        if (! is_array($restoringJournal)) {
            throw new RuntimeException('Restore committed without a durable restoring journal.');
        }

        $restoredJournal = $restoringJournal;
        $restoredJournal['repair']['status'] = 'restored';
        $restoredJournal['repair']['restored_at'] = now()->toIso8601String();
        $auditService->writeRepairJournal($restoredJournal, $journalPath);

        $this->info('KM schema rows restored to the exact checksum recorded by the audit manifest.');
        $this->line("Repair journal: {$journalPath}");

        return self::SUCCESS;
    }

    private function mergeDuplicateTransactions(array $manifest): void
    {
        foreach ($manifest['findings']['duplicate_transactions'] ?? [] as $group) {
            $rows = collect($group['rows'] ?? [])->sortBy(fn (array $row): int => (int) $row['id'])->values();
            if ($rows->count() < 2) {
                continue;
            }

            $canonical = $rows->first();
            $createdAt = $rows->pluck('created_at')->filter()->sort()->first();
            $updatedAt = $rows->pluck('updated_at')->filter()->sortDesc()->first();

            DB::table('km_transaksis')->where('id', $canonical['id'])->update([
                'status' => $rows->max(fn (array $row): int => (int) $row['status']),
                'created_at' => $createdAt,
                'updated_at' => $updatedAt,
            ]);
            DB::table('km_transaksis')
                ->whereIn('id', $rows->slice(1)->pluck('id')->all())
                ->delete();
        }
    }

    private function detachTransactionViewDependencies(array $manifest): void
    {
        $ids = collect($manifest['findings']['transaction_view_dependencies'] ?? [])
            ->pluck('id')
            ->filter(fn (mixed $id): bool => $id !== null)
            ->unique()
            ->values()
            ->all();

        if ($ids !== []) {
            DB::table('km_lihat_bukus')->whereIn('id', $ids)->update(['id_km_transaksi' => null]);
        }
    }

    private function mergeDuplicateLikes(array $manifest): void
    {
        foreach ($manifest['findings']['duplicate_likes'] ?? [] as $group) {
            $ids = collect($group['rows'] ?? [])->pluck('id')->sort()->values();
            if ($ids->count() < 2) {
                continue;
            }

            DB::table('km_sukas')->whereIn('id', $ids->slice(1)->all())->delete();
        }
    }

    private function mergeDuplicateViewCounters(array $manifest): void
    {
        foreach ($manifest['findings']['duplicate_view_counters'] ?? [] as $group) {
            $rows = collect($group['rows'] ?? [])->sortBy(fn (array $row): int => (int) $row['id'])->values();
            if ($rows->count() < 2) {
                continue;
            }

            $canonical = $rows->first();
            $total = $rows->sum(function (array $row): int {
                $value = trim((string) ($row['jumlah_lihat'] ?? ''));

                return preg_match('/^\d+$/', $value) === 1 ? (int) $value : 0;
            });

            DB::table('km_lihat_bukus')->where('id', $canonical['id'])->update([
                'jumlah_lihat' => $total,
                'created_at' => $rows->pluck('created_at')->filter()->sort()->first(),
                'updated_at' => $rows->pluck('updated_at')->filter()->sortDesc()->first(),
            ]);
            DB::table('km_lihat_bukus')
                ->whereIn('id', $rows->slice(1)->pluck('id')->all())
                ->delete();
        }
    }

    private function normalizeInvalidViewCounters(array $manifest): void
    {
        foreach ($manifest['findings']['invalid_view_counters'] ?? [] as $row) {
            $current = DB::table('km_lihat_bukus')->where('id', $row['id'])->value('jumlah_lihat');
            if ($current === null) {
                continue;
            }

            if (preg_match('/^\d+$/', trim((string) $current)) !== 1) {
                DB::table('km_lihat_bukus')->where('id', $row['id'])->update(['jumlah_lihat' => 0]);
            }
        }
    }

    private function repairInvalidAndOrphanReferences(array $manifest): void
    {
        foreach (self::REPAIR_ACTIONS as $name => [$table, $column, $action]) {
            $rows = [
                ...($manifest['findings']['invalid_user_references'][$name] ?? []),
                ...($manifest['findings']['orphans'][$name]['rows'] ?? []),
            ];
            $ids = collect($rows)->pluck('id')->filter(fn (mixed $id): bool => $id !== null)->unique()->values()->all();

            if ($ids === []) {
                continue;
            }

            if ($action === 'delete') {
                DB::table($table)->whereIn('id', $ids)->delete();
            } else {
                DB::table($table)->whereIn('id', $ids)->update([$column => null]);
            }
        }
    }

    private function lockAffectedRows(array $manifest): void
    {
        foreach ($this->affectedIds($manifest) as $table => $ids) {
            if ($ids !== [] && Schema::hasTable($table)) {
                DB::table($table)->whereIn('id', $ids)->lockForUpdate()->get(['id']);
            }
        }
    }

    private function assertAffectedRowsMatchAuditManifest(array $manifest): void
    {
        $expectedRows = $this->originalAffectedRows($manifest);

        foreach ($expectedRows as $table => $rows) {
            $currentRows = DB::table($table)
                ->whereIn('id', array_keys($rows))
                ->get()
                ->keyBy(static fn (object $row): string => (string) $row->id);

            foreach ($rows as $id => $expected) {
                $current = $currentRows->get((string) $id);
                if ($current === null
                    || ! $this->rowContainsExpectedValues((array) $current, $expected)) {
                    throw new RuntimeException(
                        "Affected row {$table}.id={$id} changed after the audit snapshot. "
                        .'KM schema repair was aborted before any business row was mutated.'
                    );
                }
            }
        }
    }

    private function assertAffectedRowsMatchPostRepairManifest(array $manifest, array $journal): void
    {
        $snapshot = $journal['repair']['affected_rows_after'] ?? null;
        if (! is_array($snapshot)) {
            throw new RuntimeException(
                'The applied manifest does not contain a post-repair affected-row snapshot. '
                .'Automatic restore is unsafe; review the manifest and use a controlled manual recovery.'
            );
        }

        $expectedKeys = [];
        foreach ($this->affectedIds($manifest) as $table => $ids) {
            foreach ($ids as $id) {
                $expectedKeys[$table.'|'.(string) $id] = true;
            }
        }

        $entries = [];
        foreach ($snapshot as $entry) {
            if (! is_array($entry)
                || ! is_string($entry['table'] ?? null)
                || ! array_key_exists('id', $entry)
                || ! is_bool($entry['exists'] ?? null)) {
                throw new RuntimeException('The post-repair affected-row snapshot is malformed.');
            }

            $table = $entry['table'];
            $id = (string) $entry['id'];
            $key = $table.'|'.$id;
            if (! isset($expectedKeys[$key]) || isset($entries[$key])) {
                throw new RuntimeException('The post-repair affected-row snapshot has unexpected or duplicate rows.');
            }

            if ($entry['exists']
                && (! is_string($entry['row_hash_sha256'] ?? null)
                    || preg_match('/^[a-f0-9]{64}$/', $entry['row_hash_sha256']) !== 1)) {
                throw new RuntimeException('The post-repair affected-row snapshot is missing its row hash.');
            }
            if (! $entry['exists'] && ($entry['row_hash_sha256'] ?? null) !== null) {
                throw new RuntimeException('The post-repair affected-row snapshot has a hash for an absent row.');
            }

            $entries[$key] = $entry;
        }

        if (count($entries) !== count($expectedKeys)) {
            throw new RuntimeException('The post-repair affected-row snapshot is incomplete.');
        }

        $entriesByTable = collect($entries)->groupBy('table');
        foreach ($entriesByTable as $table => $tableEntries) {
            $ids = $tableEntries->pluck('id')->all();
            $currentRows = DB::table($table)
                ->whereIn('id', $ids)
                ->get()
                ->keyBy(static fn (object $row): string => (string) $row->id);

            foreach ($tableEntries as $entry) {
                $id = (string) $entry['id'];
                $current = $currentRows->get($id);
                $matches = $entry['exists']
                    ? $current !== null
                        && hash_equals(
                            (string) $entry['row_hash_sha256'],
                            $this->canonicalRowHash((array) $current),
                        )
                    : $current === null;

                if (! $matches) {
                    throw new RuntimeException(
                        "Affected row {$table}.id={$id} changed after repair was applied. "
                        .'KM schema restore was aborted before any business row was mutated.'
                    );
                }
            }
        }
    }

    /**
     * @return list<array{table: string, id: mixed, exists: bool, row_hash_sha256: string|null}>
     */
    private function snapshotAffectedRows(array $manifest): array
    {
        $affectedIds = $this->affectedIds($manifest);
        ksort($affectedIds);
        $snapshot = [];

        foreach ($affectedIds as $table => $ids) {
            usort($ids, static fn (mixed $left, mixed $right): int => strnatcmp((string) $left, (string) $right));
            $currentRows = DB::table($table)
                ->whereIn('id', $ids)
                ->get()
                ->keyBy(static fn (object $row): string => (string) $row->id);

            foreach ($ids as $id) {
                $current = $currentRows->get((string) $id);
                $snapshot[] = [
                    'table' => $table,
                    'id' => $id,
                    'exists' => $current !== null,
                    'row_hash_sha256' => $current === null
                        ? null
                        : $this->canonicalRowHash((array) $current),
                ];
            }
        }

        return $snapshot;
    }

    /**
     * Hash a complete row without serializing any business value into the
     * repair journal. Length-prefixing makes the representation unambiguous
     * and also supports legacy byte strings that are not valid UTF-8.
     *
     * @param  array<string, mixed>  $row
     */
    private function canonicalRowHash(array $row): string
    {
        ksort($row, SORT_STRING);
        $context = hash_init('sha256');

        foreach ($row as $column => $value) {
            $column = (string) $column;
            hash_update($context, strlen($column).':'.$column);

            if ($value === null) {
                hash_update($context, 'N;');

                continue;
            }

            if (is_bool($value)) {
                hash_update($context, $value ? 'B1;' : 'B0;');

                continue;
            }

            $stringValue = (string) $value;
            hash_update($context, 'S'.strlen($stringValue).':'.$stringValue.';');
        }

        return hash_final($context);
    }

    /**
     * @return array<string, array<string, array<string, mixed>>>
     */
    private function originalAffectedRows(array $manifest): array
    {
        $rows = [];
        foreach ([
            'duplicate_transactions' => 'km_transaksis',
            'duplicate_likes' => 'km_sukas',
            'duplicate_view_counters' => 'km_lihat_bukus',
        ] as $finding => $table) {
            foreach ($manifest['findings'][$finding] ?? [] as $group) {
                foreach ($group['rows'] ?? [] as $row) {
                    $this->mergeExpectedRow($rows, $table, $row);
                }
            }
        }

        foreach ($manifest['findings']['invalid_view_counters'] ?? [] as $row) {
            $this->mergeExpectedRow($rows, 'km_lihat_bukus', $row);
        }

        foreach ($manifest['findings']['transaction_view_dependencies'] ?? [] as $row) {
            $this->mergeExpectedRow($rows, 'km_lihat_bukus', $row);
        }

        foreach (self::REPAIR_ACTIONS as $name => [$table]) {
            foreach ([
                ...($manifest['findings']['invalid_user_references'][$name] ?? []),
                ...($manifest['findings']['orphans'][$name]['rows'] ?? []),
            ] as $row) {
                $this->mergeExpectedRow($rows, $table, $row);
            }
        }

        return $rows;
    }

    /**
     * @param  array<string, array<string, array<string, mixed>>>  $rows
     * @param  array<string, mixed>  $row
     */
    private function mergeExpectedRow(array &$rows, string $table, array $row): void
    {
        if (! array_key_exists('id', $row)) {
            throw new RuntimeException("Audit manifest row for {$table} does not contain an id.");
        }

        $id = (string) $row['id'];
        $existing = $rows[$table][$id] ?? [];
        foreach ($row as $column => $value) {
            if (array_key_exists($column, $existing)
                && ! $this->manifestValuesMatch($existing[$column], $value)) {
                throw new RuntimeException(
                    "Audit manifest contains conflicting snapshots for {$table}.id={$id}."
                );
            }

            $existing[$column] = $value;
        }

        $rows[$table][$id] = $existing;
    }

    /**
     * @param  array<string, mixed>  $current
     * @param  array<string, mixed>  $expected
     */
    private function rowContainsExpectedValues(array $current, array $expected): bool
    {
        foreach ($expected as $column => $value) {
            if (! array_key_exists($column, $current)
                || ! $this->manifestValuesMatch($current[$column], $value)) {
                return false;
            }
        }

        return true;
    }

    private function manifestValuesMatch(mixed $actual, mixed $expected): bool
    {
        if ($actual === null || $expected === null) {
            return $actual === $expected;
        }

        return (string) $actual === (string) $expected;
    }

    private function affectedIds(array $manifest): array
    {
        $ids = [];
        foreach ([
            'duplicate_transactions' => 'km_transaksis',
            'duplicate_likes' => 'km_sukas',
            'duplicate_view_counters' => 'km_lihat_bukus',
        ] as $finding => $table) {
            foreach ($manifest['findings'][$finding] ?? [] as $group) {
                foreach ($group['rows'] ?? [] as $row) {
                    $ids[$table][] = $row['id'];
                }
            }
        }

        foreach ($manifest['findings']['invalid_view_counters'] ?? [] as $row) {
            $ids['km_lihat_bukus'][] = $row['id'];
        }

        foreach ($manifest['findings']['transaction_view_dependencies'] ?? [] as $row) {
            $ids['km_lihat_bukus'][] = $row['id'];
        }

        foreach (self::REPAIR_ACTIONS as $name => [$table]) {
            foreach ([
                ...($manifest['findings']['invalid_user_references'][$name] ?? []),
                ...($manifest['findings']['orphans'][$name]['rows'] ?? []),
            ] as $row) {
                $ids[$table][] = $row['id'];
            }
        }

        return collect($ids)
            ->map(fn (array $tableIds): array => array_values(array_unique($tableIds, SORT_REGULAR)))
            ->all();
    }

    private function restoreDeletedAndMergedRows(array $manifest): void
    {
        $originalRows = [];
        foreach ([
            'duplicate_transactions' => 'km_transaksis',
            'duplicate_likes' => 'km_sukas',
            'duplicate_view_counters' => 'km_lihat_bukus',
        ] as $finding => $table) {
            foreach ($manifest['findings'][$finding] ?? [] as $group) {
                foreach ($group['rows'] ?? [] as $row) {
                    $originalRows[$table][(string) $row['id']] = $row;
                }
            }
        }

        foreach ($manifest['findings']['invalid_view_counters'] ?? [] as $row) {
            $originalRows['km_lihat_bukus'][(string) $row['id']] = $row;
        }

        foreach ($manifest['findings']['transaction_view_dependencies'] ?? [] as $row) {
            $originalRows['km_lihat_bukus'][(string) $row['id']] = $row;
        }

        foreach (self::REPAIR_ACTIONS as $name => [$table, , $action]) {
            if ($action !== 'delete') {
                continue;
            }

            foreach ([
                ...($manifest['findings']['invalid_user_references'][$name] ?? []),
                ...($manifest['findings']['orphans'][$name]['rows'] ?? []),
            ] as $row) {
                $originalRows[$table][(string) $row['id']] = $row;
            }
        }

        foreach (['km_transaksis', 'km_sukas', 'km_insights', 'km_lihat_bukus'] as $table) {
            $rows = array_values($originalRows[$table] ?? []);
            if ($rows === []) {
                continue;
            }

            $columns = Schema::getColumnListing($table);
            $rows = array_map(
                fn (array $row): array => array_intersect_key($row, array_flip($columns)),
                $rows
            );
            $ids = array_column($rows, 'id');
            DB::table($table)->whereIn('id', $ids)->delete();
            DB::table($table)->insert($rows);
        }
    }

    private function restoreNormalizedReferences(array $manifest): void
    {
        foreach (self::REPAIR_ACTIONS as $name => [$table, $column, $action]) {
            if ($action !== 'set_null') {
                continue;
            }

            foreach ([
                ...($manifest['findings']['invalid_user_references'][$name] ?? []),
                ...($manifest['findings']['orphans'][$name]['rows'] ?? []),
            ] as $row) {
                if (array_key_exists($column, $row)) {
                    DB::table($table)->where('id', $row['id'])->update([$column => $row[$column]]);
                }
            }
        }
    }

    private function assertAutomaticallyRepairable(array $manifest): void
    {
        $counts = $manifest['summary']['blocking_counts'] ?? [];
        $manualChecks = [
            'unsupported_driver',
            'missing_tables',
            'missing_columns',
            'missing_parent_schema',
            'unsupported_engines',
            'invalid_primary_keys',
            'invalid_id_types',
            'incompatible_reference_types',
            'duplicate_primary_ids',
            'null_primary_ids',
        ];
        $manual = collect($manualChecks)
            ->filter(fn (string $check): bool => (int) ($counts[$check] ?? 0) > 0)
            ->map(fn (string $check): string => $check.'='.(int) $counts[$check])
            ->implode(', ');

        if ($manual !== '') {
            throw new RuntimeException(
                "Manifest contains schema/primary-key issues that require reviewed manual remediation: {$manual}"
            );
        }
    }

    private function assertChecksum(?string $actual, ?string $expected, string $message): void
    {
        if ($actual === null || $expected === null || ! hash_equals($expected, $actual)) {
            throw new RuntimeException($message.'. Generate a new audit manifest; no row was changed.');
        }
    }

    private function validateTargetDatabase(array $manifest): void
    {
        if (($manifest['manifest_version'] ?? null) !== KmSchemaAuditService::MANIFEST_VERSION) {
            throw new RuntimeException('Unsupported or missing KM audit manifest version.');
        }

        $currentDatabase = (string) DB::connection()->getDatabaseName();
        if (($manifest['database'] ?? null) !== $currentDatabase) {
            throw new RuntimeException(
                "Manifest targets database `{$manifest['database']}` but the active database is `{$currentDatabase}`."
            );
        }
    }

    /**
     * @param  array<string, mixed>  $repair
     * @return array<string, mixed>
     */
    private function newRepairJournal(array $manifest, string $manifestPath, array $repair): array
    {
        return [
            'journal_version' => self::REPAIR_JOURNAL_VERSION,
            'source_manifest_sha256' => $this->fileSha256($manifestPath),
            'database' => $manifest['database'],
            'repair' => $repair,
        ];
    }

    private function repairJournalPath(string $manifestPath): string
    {
        return $manifestPath.'.repair.json';
    }

    /**
     * @return array<string, mixed>|null
     */
    private function loadRepairJournal(
        KmSchemaAuditService $auditService,
        array $manifest,
        string $manifestPath,
        string $journalPath,
    ): ?array {
        $primaryError = null;

        if (File::isFile($journalPath)) {
            try {
                $journal = $this->loadManifest($journalPath);
                $this->assertRepairJournalEnvelope($journal, $manifest, $manifestPath);

                return $journal;
            } catch (Throwable $exception) {
                $primaryError = $exception;
            }
        }

        $backupPath = $journalPath.'.bak';
        if (File::isFile($backupPath)) {
            try {
                $journal = $this->loadManifest($backupPath);
                $this->assertRepairJournalEnvelope($journal, $manifest, $manifestPath);

                // Restore a verified backup without replacing the backup itself.
                $auditService->writeManifest($journal, $journalPath);
                $this->warn('Primary repair journal was recovered from its verified backup.');

                return $journal;
            } catch (Throwable $backupError) {
                throw new RuntimeException(
                    'Neither the primary nor backup KM repair journal is valid: '.$backupError->getMessage(),
                    previous: $primaryError ?? $backupError,
                );
            }
        }

        if ($primaryError !== null) {
            throw new RuntimeException(
                'The KM repair journal is invalid and no verified backup is available: '.$primaryError->getMessage(),
                previous: $primaryError,
            );
        }

        return null;
    }

    private function assertRepairJournalEnvelope(
        array $journal,
        array $manifest,
        string $manifestPath,
    ): void {
        $allowedStatuses = [
            'applying',
            'committing',
            'applied',
            'rolled_back',
            'restoring',
            'restored',
        ];

        if (($journal['journal_version'] ?? null) !== self::REPAIR_JOURNAL_VERSION
            || ($journal['database'] ?? null) !== ($manifest['database'] ?? null)
            || ! is_array($journal['repair'] ?? null)
            || ! in_array($journal['repair']['status'] ?? null, $allowedStatuses, true)
            || ! is_string($journal['source_manifest_sha256'] ?? null)
            || ! hash_equals($this->fileSha256($manifestPath), $journal['source_manifest_sha256'])) {
            throw new RuntimeException(
                'Repair journal version, database, source manifest hash, or state is invalid.'
            );
        }
    }

    /**
     * @param  array<string, mixed>|null  $journal
     * @return array{0: array<string, mixed>|null, 1: string|null}
     */
    private function reconcileRepairJournal(
        KmSchemaAuditService $auditService,
        ?array $journal,
        string $journalPath,
    ): array {
        if ($journal === null) {
            return [null, null];
        }

        $status = $journal['repair']['status'] ?? null;
        if (! in_array($status, ['applying', 'committing', 'restoring'], true)) {
            return [$journal, null];
        }

        $currentChecksum = $auditService->fingerprint()['value'];
        $beforeChecksum = $journal['repair']['before_checksum'] ?? null;
        $afterChecksum = $journal['repair']['after_checksum'] ?? null;

        if ($status === 'applying') {
            $this->assertChecksum(
                $currentChecksum,
                is_string($beforeChecksum) ? $beforeChecksum : null,
                'An interrupted repair has no committing journal and the database is not at its before state'
            );

            return [$journal, null];
        }

        if ($status === 'committing') {
            if (is_string($afterChecksum) && hash_equals($afterChecksum, $currentChecksum)) {
                $journal['repair']['status'] = 'applied';
                $journal['repair']['completed_at'] = now()->toIso8601String();
                $journal['repair']['reconciled_at'] = now()->toIso8601String();
                $auditService->writeRepairJournal($journal, $journalPath);
                $this->info('Recovered a KM repair that committed before its journal was finalized.');

                return [$journal, 'applied'];
            }

            if (is_string($beforeChecksum) && hash_equals($beforeChecksum, $currentChecksum)) {
                $journal['repair']['status'] = 'rolled_back';
                $journal['repair']['rolled_back_at'] = now()->toIso8601String();
                $journal['repair']['reconciled_at'] = now()->toIso8601String();
                $auditService->writeRepairJournal($journal, $journalPath);

                return [$journal, null];
            }

            throw new RuntimeException(
                'Interrupted KM repair cannot be reconciled: the database matches neither before nor after checksum.'
            );
        }

        $restoredChecksum = $journal['repair']['restored_checksum'] ?? $beforeChecksum;
        if (is_string($restoredChecksum) && hash_equals($restoredChecksum, $currentChecksum)) {
            $journal['repair']['status'] = 'restored';
            $journal['repair']['restored_at'] = now()->toIso8601String();
            $journal['repair']['reconciled_at'] = now()->toIso8601String();
            $auditService->writeRepairJournal($journal, $journalPath);
            $this->info('Recovered a KM restore that committed before its journal was finalized.');

            return [$journal, 'restored'];
        }

        if (is_string($afterChecksum) && hash_equals($afterChecksum, $currentChecksum)) {
            $journal['repair']['status'] = 'applied';
            $journal['repair']['restore_rolled_back_at'] = now()->toIso8601String();
            $journal['repair']['reconciled_at'] = now()->toIso8601String();
            $auditService->writeRepairJournal($journal, $journalPath);

            return [$journal, null];
        }

        throw new RuntimeException(
            'Interrupted KM restore cannot be reconciled: the database matches neither repaired nor restored checksum.'
        );
    }

    private function fileSha256(string $path): string
    {
        $checksum = File::isFile($path) ? hash_file('sha256', $path) : false;
        if (! is_string($checksum)) {
            throw new RuntimeException("Unable to checksum KM audit manifest: {$path}");
        }

        return $checksum;
    }

    private function guardMutation(bool $apply, bool $restore): void
    {
        $database = (string) DB::connection()->getDatabaseName();

        if (app()->environment('testing')) {
            if (! str_ends_with($database, '_testing')) {
                throw new RuntimeException(
                    'Automated KM schema repair requires APP_ENV=testing and DB_DATABASE ending with _testing.'
                );
            }

            return;
        }

        if (! $apply) {
            throw new RuntimeException(
                'Non-testing repair or restore requires the explicit --apply flag after a verified backup.'
            );
        }

        if ($restore && ! $apply) {
            throw new RuntimeException('Non-testing restore requires both --restore and --apply.');
        }
    }

    private function renderPlan(array $manifest, ?array $journal): void
    {
        $this->info('KM schema repair manifest');
        $this->line('Database: '.($manifest['database'] ?? 'unknown'));
        $this->line('Generated: '.($manifest['generated_at'] ?? 'unknown'));
        $this->line('Repair status: '.($journal['repair']['status'] ?? 'not_applied'));
        $this->table(
            ['Finding', 'Count'],
            collect($manifest['summary']['blocking_counts'] ?? [])
                ->filter(fn (int $count): bool => $count > 0)
                ->map(fn (int $count, string $finding): array => [$finding, $count])
                ->values()
                ->all()
        );
    }

    private function loadManifest(string $path): array
    {
        if (! File::isFile($path) || ! File::isReadable($path)) {
            throw new RuntimeException("Manifest is not readable: {$path}");
        }

        $manifest = json_decode(File::get($path), true, flags: JSON_THROW_ON_ERROR);
        if (! is_array($manifest)) {
            throw new RuntimeException('Manifest root must be a JSON object.');
        }

        return $manifest;
    }

    private function resolveManifestPath(string $path): string
    {
        if (preg_match('/^[A-Za-z]:[\\\\\/]/', $path) === 1
            || str_starts_with($path, '/')
            || str_starts_with($path, '\\')) {
            return $path;
        }

        return base_path($path);
    }
